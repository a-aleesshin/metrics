// Staticlint — multichecker статического анализа проекта metrics.
//
// # Механизм запуска
//
// Multichecker построен на golang.org/x/tools/go/analysis/multichecker:
// функция multichecker.Main получает список анализаторов и превращает бинарник
// в утилиту с интерфейсом go vet. Анализируемые пакеты передаются аргументами.
//
// Запуск без сборки (из корня репозитория):
//
//	go run ./cmd/staticlint ./...
//
// Или собрать бинарник и запустить его:
//
//	go build -o staticlint ./cmd/staticlint
//	./staticlint ./...
//
// Полезные флаги (стандартные для multichecker):
//
//	./staticlint help            — список всех анализаторов с описанием
//	./staticlint help osexit     — справка по конкретному анализатору
//	./staticlint -osexit ./...   — запустить только один анализатор
//	./staticlint -SA1000=false ./... — исключить анализатор из прогона
//
// Ненулевой код выхода означает, что найдены замечания.
//
// # Состав анализаторов
//
// Стандартные анализаторы golang.org/x/tools/go/analysis/passes:
//
//   - appends — вызов append без добавляемых значений;
//   - asmdecl — несоответствие ассемблерных файлов Go-декларациям;
//   - assign — бесполезные присваивания вида x = x;
//   - atomic — типичные ошибки использования sync/atomic;
//   - bools — подозрительные булевы выражения (x && x и т. п.);
//   - buildtag — некорректные build-теги;
//   - composite — неключевые составные литералы импортированных структур;
//   - copylock — копирование значений, содержащих sync.Mutex и другие блокировки;
//   - defers — типичные ошибки в defer (например, defer t.Since(...));
//   - directive — некорректные директивы компилятора (//go:...);
//   - errorsas — передача не-указателя во второй аргумент errors.As;
//   - httpresponse — использование http.Response до проверки ошибки;
//   - ifaceassert — заведомо невозможные type assertion между интерфейсами;
//   - loopclosure — захват переменной цикла замыканием, переживающим итерацию;
//   - lostcancel — потеря cancel-функции context.WithCancel/WithTimeout;
//   - nilfunc — бессмысленные сравнения функции с nil;
//   - printf — несоответствие формат-строк и аргументов в Printf-подобных функциях;
//   - shift — сдвиги, превышающие разрядность типа;
//   - sigchanyzer — небуферизованные каналы в signal.Notify;
//   - sortslice — некорректные аргументы sort.Slice;
//   - stdmethods — сигнатуры известных методов (Error, String, MarshalJSON...),
//     не совпадающие с каноническими;
//   - stringintconv — подозрительные преобразования string(int);
//   - structtag — некорректные теги структур;
//   - testinggoroutine — вызовы t.Fatal из горутин в тестах;
//   - tests — неправильные сигнатуры Test/Benchmark/Example-функций;
//   - timeformat — time.Format с шаблоном 2006-02-01 (перепутанные месяц и день);
//   - unmarshal — передача не-указателя в json.Unmarshal и аналоги;
//   - unreachable — недостижимый код;
//   - unsafeptr — некорректные преобразования uintptr в unsafe.Pointer;
//   - unusedresult — неиспользованные результаты вызовов без побочных эффектов
//     (fmt.Errorf, errors.New и т. п.).
//
// Анализаторы staticcheck.io (honnef.co/go/tools):
//
//   - все анализаторы класса SA (staticcheck) — поиск багов и подозрительных
//     конструкций: некорректная конкурентность, неправильное использование
//     стандартной библиотеки, бесполезный код и т. д.;
//   - S1005 (класс simple) — упрощение: лишняя переменная при распаковке;
//   - ST1013 (класс stylecheck) — именованные константы net/http вместо
//     магических чисел HTTP-статусов;
//   - QF1010 (класс quickfix) — печать байтового среза через %s
//     вместо явного преобразования string(...).
//
// Публичные анализаторы:
//
//   - bodyclose (github.com/timakin/bodyclose) — проверяет, что res.Body
//     HTTP-ответа всегда закрывается
//   - nilerr (github.com/gostaticanalysis/nilerr) — находит return nil
//     в ветке, где err заведомо не nil (потерянная ошибка).
//
// Собственный анализатор:
//
//   - osexit (cmd/staticlint/osexit) — запрещает прямой вызов os.Exit
//     в функции main пакета main. Прямой os.Exit обрывает процесс без
//     выполнения defer и сброса буферов; вместо него логику следует выносить
//     в функцию с ошибкой и завершаться в одной точке.
