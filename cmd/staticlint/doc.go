// Staticlint — статический анализатор проекта metrics на основе
// golang.org/x/tools/go/analysis/singlechecker.
//
// # Механизм запуска
//
// Бинарник построен через singlechecker.Main: он получает один анализатор
// и превращает программу в утилиту с интерфейсом go vet. Анализируемые
// пакеты передаются аргументами.
//
// Запуск без сборки (из корня репозитория):
//
//	go run ./cmd/staticlint ./...
//
// Или собрать бинарник и запустить его:
//
//	go build -o staticlint ./cmd/staticlint
//	./staticlint ./...
//
// Справка по анализатору и флагам:
//
//	./staticlint -help
//
// Ненулевой код выхода означает, что найдены замечания.
//
// # Анализатор
//
// osexit (cmd/staticlint/osexit) — запрещает прямой вызов os.Exit в функции
// main пакета main. Прямой os.Exit обрывает процесс без выполнения defer
// и сброса буферов; вместо него логику следует выносить в функцию,
// возвращающую ошибку, и завершаться в одной точке (например, log.Fatal).
// Сгенерированные файлы (в том числе тестовые main от go test) пропускаются.
//
// Расширенный набор анализаторов (стандартные passes, staticcheck SA/S/ST/QF,
// bodyclose, nilerr и тот же osexit) доступен отдельным бинарником —
// см. cmd/multichecker.
